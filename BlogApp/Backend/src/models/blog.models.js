import mongoose from "mongoose";

const blogSchema = new mongoose.Schema(
  {
    coverImage: {
      type: String,
      require: true,
      default: ""
    },
    title: {
      type: String,
      required: true,
      trim: true,
    },

    content: {
      type: String,
      required: true,
    },

    author: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },

    likes: [
      {
        type: mongoose.Schema.Types.ObjectId,
        ref: "User",
      },
    ],
  },
  { timestamps: true }
);

export default mongoose.model("Blog", blogSchema);
